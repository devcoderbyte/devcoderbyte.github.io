"""Fit per-task-type baselines and AI ranges from raw exports.

Reads only the exported files (tickets, timesheets, P&L, rate card, contract,
incident costs, AI pilot logs) and writes aggregated calibration: no ticket
rows, no client names. That calibration file is the only thing the website uses.

Usage: python3 fit.py DATA_DIR OUT_JSON
"""
import json, sys
import numpy as np
import pandas as pd

D, OUT = sys.argv[1], sys.argv[2]
rng = np.random.default_rng(1)

def q(a, p): return float(np.percentile(a, p))
def beta_q(k, n, ps=(10, 50, 90)):
    s = rng.beta(1 + k, 1 + n - k, 200000)
    return [float(np.percentile(s, p)) for p in ps]
def boot_mean(a, ps=(10, 50, 90), B=4000):
    a = np.asarray(a); idx = rng.integers(0, len(a), (B, len(a)))
    m = a[idx].mean(axis=1)
    return [float(np.percentile(m, p)) for p in ps]

t = pd.read_csv(f'{D}/tickets.csv', parse_dates=['opened_at', 'resolved_at'])
t['month'] = t.opened_at.dt.to_period('M')
months = sorted(t.month.unique()); n_m = len(months)
ts = pd.read_csv(f'{D}/timesheets.csv'); pl = pd.read_csv(f'{D}/pnl_monthly.csv')
rate = pd.read_csv(f'{D}/rate_card.csv').set_index('level')
contract = json.load(open(f'{D}/contract.json'))
inc = pd.read_csv(f'{D}/incident_costs.csv')
runs = pd.read_csv(f'{D}/ai_pilot_runs.csv'); meta = json.load(open(f'{D}/ai_pilot_meta.json'))

# ---- per task type baselines -------------------------------------------------
types = {}
for cat, g in t.groupby('category'):
    vol = g.groupby('month').size().reindex(months, fill_value=0).values
    x = np.arange(n_m); slope = np.polyfit(x, np.log(np.maximum(vol, 1)), 1)[0]
    first = g[g.reopened == 0].effort_hours; re = g[g.reopened == 1].effort_hours
    rework = float(re.mean() / first.mean() - 1) if len(re) >= 5 else 0.0
    types[cat] = dict(
        priority=g.priority.mode()[0],
        volume_month=dict(mean=round(float(vol.mean()), 1), sd=round(float(vol.std(ddof=1)), 1), last3=round(float(vol[-3:].mean()), 1)),
        monthly_growth=round(float(slope), 4),
        handle_hours=dict(p10=round(q(first, 10), 2), median=round(q(first, 50), 2), mean=round(float(first.mean()), 3), p90=round(q(first, 90), 2)),
        mean_effort_all=round(float(g.effort_hours.mean()), 3),
        reopen_rate=round(float(g.reopened.mean()), 4),
        rework_extra=round(rework, 3),
        junior_share_hours=round(float(g[g.assignee_level == 'junior'].effort_hours.sum() / g.effort_hours.sum()), 3),
        sla_breach_rate=round(float(g.sla_breached.mean()), 4),
        n_tickets=int(len(g)))

# ---- capacity from timesheets ------------------------------------------------
cap = {}
for lvl, g in ts.groupby('level'):
    cap[lvl] = dict(paid_hours=float(rate.loc[lvl, 'paid_hours']),
                    other_share=round(float((g.other_hours / g.paid_hours).mean()), 4),
                    other_share_sd=round(float((g.other_hours / g.paid_hours).std(ddof=1)), 4),
                    monthly_cost=float(rate.loc[lvl, 'monthly_cost']),
                    headcount_now=int(g.headcount.iloc[-1]))
overhead = round(float(pl.tools_overhead.mean()), 0)
other_noise = dict(mean=round(float(pl.other_cost.mean()), 1), sd=round(float(pl.other_cost.std()), 1))

# SLA: overall breach rate and its month-to-month spread
br = t.groupby('month').sla_breached.mean().values
sla = dict(breach_rate_mean=round(float(br.mean()), 4), breach_rate_sd=round(float(br.std(ddof=1)), 4))

# ---- incident costs: what an escaped error tends to cost (P3-class) ----------
p3 = inc[inc.priority == 'P3']
esc_cost = (p3.remediation_cost + p3.client_credit).values
escaped_cost = dict(p10=round(q(esc_cost, 10)), median=round(q(esc_cost, 50)), p90=round(q(esc_cost, 90)), n=int(len(esc_cost)),
                    basis='P3 incidents: remediation + client credit')

# ---- AI pilot ----------------------------------------------------------------
pm = [pd.Period(m, 'M') for m in meta['pilot_months']]
pilot_t = t[t.month.isin(pm)]
ai = {}
for cat, g in runs.groupby('category'):
    n_elig = int((pilot_t.category == cat).sum()); n = len(g)
    wrong = int((g.human_redo + g.escaped_to_client).sum()); esc = int(g.escaped_to_client.sum())
    ai[cat] = dict(
        runs=n, eligible=n_elig,
        automation_rate=[round(v, 4) for v in beta_q(n, n_elig)],
        error_rate=[round(v, 4) for v in beta_q(wrong, n)],
        review_minutes_mean=[round(v, 2) for v in boot_mean(g.review_minutes)],
        token_cost_mean=[round(v, 4) for v in boot_mean(g.token_cost_usd)],
        observed=dict(errors=wrong, escaped=esc))
allw = int((runs.human_redo + runs.escaped_to_client).sum()); alle = int(runs.escaped_to_client.sum())
catch = [round(v, 4) for v in beta_q(allw - alle, allw)]

cal = dict(
    _note='Fitted from SYNTHETIC exports generated by generate_synthetic.py. Aggregates only, no ticket rows.',
    months=[str(m) for m in months], types=types, capacity=cap, overhead_month=overhead, other_cost=other_noise,
    contract=dict(monthly_fee=contract['monthly_fee'], term_months=contract['term_months'],
                  sla_target_pct=contract['sla_target_pct'], service_credits=contract['service_credits'],
                  overtime_multiplier=contract['overtime_multiplier']),
    sla=sla, escaped_error_cost=escaped_cost,
    ai=dict(types=ai, catch_rate=catch, platform_fee_month=meta['platform_fee_month'],
            eval_runs_month=meta['eval_runs_month'], guardrail_overhead_pct=meta['guardrail_overhead_pct'],
            model=meta['model']),
    history=dict(volume_by_month={c: [int(v) for v in t[t.category == c].groupby('month').size().reindex(months, fill_value=0).values] for c in types},
                 headcount_by_month={lvl: [int(v) for v in g.headcount.values] for lvl, g in ts.groupby('level')},
                 pnl=pl[['month', 'revenue', 'delivery_cost', 'gross_profit']].to_dict('records'),
                 ticket_hours_by_month=[round(float(v), 1) for v in t.groupby('month').effort_hours.sum().values]))
json.dump(cal, open(OUT, 'w'), indent=1)

# ---- readable report ------------------------------------------------------------
print(f"{'task type':16} {'pri':3} {'vol/mo':>7} {'growth':>7} {'handle p10/med/p90 h':>22} {'reopen':>7} {'rework':>7} {'junior':>7} {'SLA br':>7}")
for c, v in sorted(types.items(), key=lambda kv: -kv[1]['volume_month']['mean']):
    h = v['handle_hours']
    print(f"{c:16} {v['priority']:3} {v['volume_month']['mean']:7.0f} {v['monthly_growth']*100:6.1f}% {h['p10']:6.2f}/{h['median']:5.2f}/{h['p90']:6.2f}   {v['reopen_rate']*100:6.1f}% {v['rework_extra']*100:6.0f}% {v['junior_share_hours']*100:6.0f}% {v['sla_breach_rate']*100:6.1f}%")
print('\ncapacity:', {k: dict(other_share=v['other_share'], headcount=v['headcount_now']) for k, v in cap.items()}, 'overhead', overhead)
print('SLA breach rate mean %.2f%% sd %.2f%%' % (sla['breach_rate_mean']*100, sla['breach_rate_sd']*100))
print('escaped error cost (P3 incidents) p10/med/p90:', escaped_cost['p10'], escaped_cost['median'], escaped_cost['p90'])
print(f"\n{'AI pilot':16} {'runs':>5} {'automation p10/50/90':>22} {'error p10/50/90':>20} {'review min':>18} {'$/run':>18}")
for c, v in ai.items():
    a, e, r, k = v['automation_rate'], v['error_rate'], v['review_minutes_mean'], v['token_cost_mean']
    print(f"{c:16} {v['runs']:5} {a[0]*100:6.1f}/{a[1]*100:4.1f}/{a[2]*100:4.1f}%   {e[0]*100:5.1f}/{e[1]*100:4.1f}/{e[2]*100:4.1f}%  {r[0]:5.1f}/{r[1]:4.1f}/{r[2]:4.1f}  {k[0]:.3f}/{k[1]:.3f}/{k[2]:.3f}")
print('catch rate p10/50/90:', catch)
