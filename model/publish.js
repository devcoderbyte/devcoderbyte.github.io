// Write the public calibration file: fitted ranges + proof summaries only. No ticket rows,
// no monthly P&L, no headcount history. Run: node model/publish.js CALIBRATION_JSON FORECAST_SCORE_JSON
const fs = require('fs'), path = require('path');
const M = require('../tools/ai-roi-model.js');
const cal = JSON.parse(fs.readFileSync(path.resolve(process.argv[2])));
const score = process.argv[3] ? JSON.parse(fs.readFileSync(path.resolve(process.argv[3]))) : null;
const bt = M.backtest(cal);
const pub = JSON.parse(JSON.stringify(cal));
delete pub.history;                                  // raw monthly history stays private
pub.proof = {
  backtest: { months: cal.months.length, mapeHours: bt.mapeHours, mapeRevenue: bt.mapeRevenue, mapeCost: bt.mapeCost,
              maxMonthlyCostErr: bt.maxMonthlyCostErr, totalProfitErr: bt.totalProfitErr },
  forecast: score };
const n = Object.values(cal.types).reduce((s, t) => s + t.n_tickets, 0);
const runs = Object.values(cal.ai.types).reduce((s, t) => s + t.runs, 0);
pub.summary = { tickets: n, pilotRuns: runs, synthetic: true };
fs.writeFileSync(path.join(__dirname, '../tools/ai-roi-calibration.js'),
  '/* Fitted ranges for the AI ROI calculator (Advanced mode). Generated by model/publish.js.\n   Aggregates only: no ticket rows, no monthly P&L. Source data: SYNTHETIC account (model/generate_synthetic.py). */\n' +
  'window.AICAL = ' + JSON.stringify(pub) + ';\n');
console.log('published', (fs.statSync(path.join(__dirname, '../tools/ai-roi-calibration.js')).size / 1024).toFixed(1) + ' KB', 'tickets', n, 'runs', runs);
